"""Read and change the dev command in a site's .lerd.yaml.

Python has no YAML parser in its standard library, so this understands only
the shape Lerd itself writes: a top-level `proxy:` block whose `command` and
`port` are single-line scalars. Anything else is refused rather than guessed,
and a change rewrites the one `command` line, leaving every other byte alone.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import List, Optional

RUSTYARD_MARKER = "# Generated by Rustyard"
TOP_KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*):(.*)$")
NESTED_KEY = re.compile(r"^([ ]+)([A-Za-z_][A-Za-z0-9_-]*):(?:[ ]+(.*?))?[ ]*$")


class Unsupported(ValueError):
    """The file is valid for Lerd but not in a shape this module edits."""


@dataclass
class Proxy:
    command: Optional[str]
    port: Optional[int]
    command_line: Optional[int]  # index into the file's lines
    indent: str
    line: int = 0  # the `proxy:` line itself


@dataclass
class LerdYaml:
    lines: List[str]
    proxy: Optional[Proxy]
    top_keys: List[str]

    @property
    def rustyard(self) -> bool:
        return any(line.startswith(RUSTYARD_MARKER) for line in self.lines[:3])


def parse(text: str) -> LerdYaml:
    if "\t" in text:
        raise Unsupported(".lerd.yaml contains tabs")
    lines = text.splitlines(keepends=True)
    top_keys = []
    proxy = None
    i = 0
    while i < len(lines):
        raw = lines[i].rstrip("\r\n")
        marker = _document_marker(raw)
        if marker:
            # One leading document marker is fine; a second document is not.
            if top_keys or marker == "...":
                raise Unsupported(".lerd.yaml holds more than one document")
            i += 1
            continue
        if not raw.strip() or raw.lstrip().startswith("#") or raw.startswith((" ", "-")):
            i += 1
            continue
        match = TOP_KEY.match(raw)
        if not match:
            raise Unsupported(f"line {i + 1} is not a plain key")
        top_line = i
        key, rest = match.group(1), match.group(2).strip()
        if key in top_keys:
            raise Unsupported(f"`{key}` appears twice")
        top_keys.append(key)
        _single_line(rest, key, i)
        if key == "proxy":
            if _strip_plain_comment(rest):
                raise Unsupported("`proxy` must be a block, not an inline value")
            proxy, i = _parse_proxy(lines, i + 1)
            proxy.line = top_line
            continue
        i += 1
    return LerdYaml(lines=lines, proxy=proxy, top_keys=top_keys)


def _parse_proxy(lines: List[str], start: int):
    command = None
    command_line = None
    port = None
    indent = None
    i = start
    while i < len(lines):
        raw = lines[i].rstrip("\r\n")
        if raw and not raw.startswith(" "):
            if raw.lstrip().startswith("#"):
                i += 1
                continue
            break
        if not raw.strip() or raw.strip().startswith("#"):
            i += 1
            continue
        match = NESTED_KEY.match(raw)
        if not match:
            raise Unsupported(f"line {i + 1} in `proxy` is not a single-line key")
        this_indent, key, value = match.group(1), match.group(2), match.group(3)
        _single_line((value or "").strip(), "proxy." + key, i)
        if indent is None:
            indent = this_indent
        elif this_indent != indent:
            raise Unsupported(f"line {i + 1} in `proxy` is nested deeper than its keys")
        if key in ("command", "port"):
            if value is None or not value.strip():
                raise Unsupported(f"`proxy.{key}` spans several lines")
            if i + 1 < len(lines) and _continues(lines[i + 1], indent):
                raise Unsupported(f"`proxy.{key}` spans several lines")
            scalar = scalar_value(value)
            if key == "command":
                command, command_line = scalar, i
            else:
                try:
                    port = int(scalar)
                except ValueError:
                    raise Unsupported("`proxy.port` is not a number") from None
        i += 1
    return Proxy(command=command, port=port, command_line=command_line, indent=indent or "  "), i


def _continues(line: str, indent: str) -> bool:
    raw = line.rstrip("\r\n")
    return bool(raw.strip()) and raw.startswith(indent + " ") and not raw.strip().startswith("#")


def _document_marker(raw: str) -> Optional[str]:
    for marker in ("---", "..."):
        if raw == marker or raw.startswith(marker + " ") or raw.startswith(marker + "\t"):
            return marker
    return None


def _strip_plain_comment(value: str) -> str:
    # In a plain (unquoted) scalar, quotes are ordinary characters and a
    # comment starts at the first `#` that follows whitespace.
    for index, char in enumerate(value):
        if char == "#" and (index == 0 or value[index - 1] in " \t"):
            return value[:index].rstrip()
    return value


def _single_line(value: str, key: str, index: int) -> None:
    """Refuse a quoted value that goes on past its line: the lines after it
    would look like keys to this reader while YAML reads them as text."""
    if value[:1] in ("'", '"'):
        try:
            scalar_value(value)
        except Unsupported:
            raise Unsupported(f"`{key}` on line {index + 1} is a quoted value this reader cannot follow") from None


def scalar_value(value: str) -> str:
    value = value.strip()
    if value.startswith('"'):
        end = _closing_double_quote(value)
        rest = value[end + 1 :].strip()
        if rest and not rest.startswith("#"):
            raise Unsupported("unexpected text after a quoted value")
        try:
            return json.loads(value[: end + 1])
        except ValueError:
            raise Unsupported("a double-quoted value uses escapes this reader does not know") from None
    if value.startswith("'"):
        index = 1
        out = []
        while index < len(value):
            char = value[index]
            if char == "'":
                if value[index + 1 : index + 2] == "'":
                    out.append("'")
                    index += 2
                    continue
                rest = value[index + 1 :].strip()
                if rest and not rest.startswith("#"):
                    raise Unsupported("unexpected text after a quoted value")
                return "".join(out)
            out.append(char)
            index += 1
        raise Unsupported("a single-quoted value is not closed")
    plain = _strip_plain_comment(value)
    if not plain or plain[0] in "[{&*!|>%@`" or ": " in plain:
        raise Unsupported(f"the value {plain!r} is not a plain single-line scalar")
    return plain


def _closing_double_quote(value: str) -> int:
    index = 1
    while index < len(value):
        if value[index] == "\\":
            index += 2
            continue
        if value[index] == '"':
            return index
        index += 1
    raise Unsupported("a double-quoted value is not closed")


def with_command(doc: LerdYaml, command: str) -> str:
    """The file text with proxy.command set to command, everything else kept."""
    if doc.proxy is None:
        raise Unsupported("the file has no `proxy` block")
    line = f"{doc.proxy.indent}command: {json.dumps(command)}"
    lines = list(doc.lines)
    if doc.proxy.command_line is None:
        # Add it as the block's first key, right after the top-level `proxy:`.
        index = doc.proxy.line
        lines.insert(index + 1, line + _ending(lines[index]))
    else:
        old = lines[doc.proxy.command_line]
        lines[doc.proxy.command_line] = line + _ending(old)
    return "".join(lines)


def _ending(line: str) -> str:
    if line.endswith("\r\n"):
        return "\r\n"
    return "\n"


def new_file(command: str, port: int) -> str:
    return (
        "# Written by lerd rust:setup. Run `lerd link` to review and approve the dev command.\n"
        "secured: true\n"
        "proxy:\n"
        f"  command: {json.dumps(command)}\n"
        f"  port: {int(port)}\n"
    )
